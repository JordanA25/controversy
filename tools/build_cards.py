"""Extract the 4x50 statement cards from the planning doc into js/cards.js."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
text = (root / "Controversy Planning Doc.txt").read_text(encoding="utf-8")
levels, cur = [], None
for line in text.splitlines():
    line = line.strip()
    m = re.match(r"Level (\d): ([^:]+): (\w+)", line)
    if m:
        cur = {"id": int(m[1]), "name": m[2].strip(), "color": m[3].lower(), "cards": []}
        levels.append(cur)
        continue
    if line.startswith("THE BOX WILL INCLUDE"):
        cur = None
    if cur and line:
        card = re.sub(r"^\d+\.\s*", "", line).replace("’", "'")
        if card not in cur["cards"]:
            cur["cards"].append(card)
for lv in levels:
    print(lv["id"], lv["name"], lv["color"], len(lv["cards"]))
(root / "js" / "cards.js").write_text(
    "// Generated by tools/build_cards.py from the planning doc. Do not hand-edit.\n"
    "window.LEVELS = " + json.dumps(levels, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
